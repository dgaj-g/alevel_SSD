#!/usr/bin/env python3
# Writes js/data/f.js: the four practicals. Each option's result is captured from dotnet; verify_all.py re-runs every one.
import json, os, re, sys
sys.path.insert(0, os.path.dirname(__file__))
from probe import run
WD = 'probe'
CLOSE = 'Console.WriteLine();\nConsole.WriteLine("Press Enter to close this window.");\nConsole.ReadLine();'
def fill(src, pick):
    out = []
    for l in src.split('\n'):
        m = re.match(r'^(\s*)\{\{(\d+)\}\}$', l)
        if not m: out.append(l); continue
        t = pick(int(m.group(2)))
        if t: out += [m.group(1) + x for x in t.split('\n')]
    return '\n'.join(out)
def dedupe(errs):
    seen = []
    for c, m in errs:
        if [c, m] not in seen: seen.append([c, m])
    return seen
def capture(methods, main, stdin, prompts, seed=False):
    dm = main.replace('new Random()', 'new Random(7)') if seed else main
    r = run(methods, dm, '\n'.join(stdin) + '\n' if stdin else '', wd=WD)
    cs = {'methods': methods, 'main': main, 'stdin': '\n'.join(stdin) + '\n' if stdin else ''}
    if seed: cs['seed'] = 7
    if not r['built']:
        msgs = [list(e) for e in r['errors']]
        return {'cs': cs, 'expect': {'errors': sorted({m[0] for m in msgs}), 'msgs': msgs}}
    o = r['out']; ev = []; pos = 0
    for line in stdin:
        hits = [(o.find(p, pos), p) for p in prompts if o.find(p, pos) >= 0]
        if not hits: break
        at, p = min(hits); end = at + len(p)
        ev.append(['out', o[pos:end]]); ev.append(['in', line]); pos = end
    if o[pos:]: ev.append(['out', o[pos:]])
    x = {'out': o}
    if r['crashed']:
        first = r['stderr'].split('\n')[0]; x['crash'] = True; x['err'] = first
        m = re.match(r'Unhandled exception\. System\.(\w+): (.*)', first)
        ev.append(['crash', m.group(1), m.group(2)])
    return {'cs': cs, 'expect': x, 'ev': ev}
def practical(P):
    stdin = P['bookIn']; prompts = P['prompts']; seed = P.get('seed')
    right = lambda k: next(s['line'] for s in P['steps'] if s['k'] == k)
    def prog(pick): return fill(P['methods'], pick), fill(P['main'], pick)
    m, mn = prog(right)
    P['run'] = capture(m, mn, stdin, prompts, seed)
    assert 'errors' not in P['run']['expect'], P['run']
    assert not P['run']['expect'].get('crash')
    for s in P['steps']:
        for w in s['wrong']:
            m2, mn2 = prog(lambda k: w['t'] if k == s['k'] else right(k))
            w.update(capture(m2, mn2, stdin, prompts, seed))
            if w['expect'].get('out') == P['run']['expect']['out']: print('SAME AS RIGHT', P['id'], w['t'])
    O = P['own']
    O['cs'] = P['run']['cs']; O['expect'] = P['run']['expect']; O['ev'] = P['run']['ev']
    S = P.pop('slips'); vers = []; seen = []
    for code, why in S['versions']:
        c = capture(code, S['main'], [], [])
        x = c['expect']
        say = 'It will not build.' if 'errors' in x else 'It crashes.' if x.get('crash') else f"It prints {x['out'].strip()}"
        if say not in seen: seen.append(say)
        vers.append({'code': code, 'say': say, 'why': why, **c})
    for v in vers: v['a'] = seen.index(v.pop('say'))
    P['bugs'] = []
    for s in P['steps']:
        for w in s['wrong']:
            lines = (w['cs']['methods'] + '\n' + w['cs']['main']).split('\n')
            if sum(1 for l in lines if l.strip() == w['t']) != 1: continue  # the clinic asks for one faulty line, so it must be the only one like it
            others = [x for x in s['wrong'] if x is not w]
            P['bugs'].append({'part': P['part'], 'prog': P['name'], 'should': P['building'], 'bad': w['t'], 'also': [],
                'cs': w['cs'], 'expect': w['expect'], **({'ev': w['ev']} if 'ev' in w else {}),
                'fixes': [{'t': s['line'], 'ok': True, 'why': s['brief']}] + [{'t': x['t'], 'ok': False, 'why': x['why']} for x in others],
                'fixed': P['run']})
    P['slipSet'] = {'intro': S['intro'], 'outcomes': seen, 'versions': vers, 'note': S['note']}
    return P
exec(open(os.path.join(os.path.dirname(__file__), 'f_src.py')).read())
out = [practical(p) for p in PRACTICALS]
bugs = [b for p in out for b in p.pop('bugs')]
src = "// Zone F: the four practicals (booklet section 11). Generated by verify/gen_f.py + f_src.py; results come from dotnet.\nexport const PRACTICALS = " + json.dumps(out, ensure_ascii=False, indent=0) + ";\nexport const BUGS = " + json.dumps(bugs, ensure_ascii=False, indent=0) + ";\n"
open(os.path.join(os.path.dirname(__file__), '..', 'js', 'data', 'f.js'), 'w').write(src)
